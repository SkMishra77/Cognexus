"""ZIP builder — bundles lab notebooks into a downloadable archive.

Creates a ZIP containing all .ipynb files + requirements.txt + README.md.
"""

import io
import json
import re
import zipfile

import nbformat


def _safe_filename(concept: str) -> str:
    """Convert a concept name into a safe filename."""
    name = re.sub(r"[^\w\s-]", "", concept).strip()
    name = re.sub(r"[\s]+", "_", name)
    return name or "lab"


def _extract_requirements(nb_dict: dict) -> set[str]:
    """Extract pip packages from !pip install cells in a notebook."""
    requirements: set[str] = set()
    cells = nb_dict.get("cells", [])
    for cell in cells:
        if cell.get("cell_type") != "code":
            continue
        source = cell.get("source", "")
        if isinstance(source, list):
            source = "".join(source)
        if "!pip install" in source:
            # Extract packages from lines like "!pip install numpy torch --quiet"
            for line in source.split("\n"):
                line = line.strip()
                if line.startswith("!pip install"):
                    parts = line.replace("!pip install", "").split()
                    for pkg in parts:
                        pkg = pkg.strip()
                        if pkg and not pkg.startswith("-"):
                            requirements.add(pkg)
    return requirements


def _build_readme(paper_title: str, lab_entries: list[tuple[str, str]]) -> str:
    """Build a README.md for the lab ZIP.

    Args:
        paper_title: Title of the paper.
        lab_entries: List of (filename, concept_name) tuples.
    """
    lines = [
        f"# {paper_title} — Experiment Labs",
        "",
        "Generated by [Cognexus](https://github.com/cognexus).",
        "",
        "## Notebooks",
        "",
    ]
    for filename, concept in lab_entries:
        lines.append(f"- **{filename}** — {concept}")
    lines.extend(
        [
            "",
            "## Setup",
            "",
            "```bash",
            "pip install -r requirements.txt",
            "jupyter lab",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def build_labs_zip(labs: list, paper_title: str) -> bytes:
    """Create ZIP bytes containing all .ipynb files + requirements.txt + README.md.

    Args:
        labs: List of GeneratedLab ORM objects with .concept and .notebook_json.
        paper_title: Title of the paper for the README.

    Returns:
        Raw ZIP bytes ready to be returned in a streaming response.
    """
    buf = io.BytesIO()
    all_requirements: set[str] = set()
    lab_entries: list[tuple[str, str]] = []

    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for lab in labs:
            nb_dict = lab.notebook_json
            if nb_dict is None:
                continue

            reqs = _extract_requirements(nb_dict)
            all_requirements.update(reqs)

            filename = f"{_safe_filename(lab.concept)}_lab.ipynb"
            lab_entries.append((filename, lab.concept))

            # Write notebook
            try:
                nb = nbformat.reads(json.dumps(nb_dict), as_version=4)
                zf.writestr(filename, nbformat.writes(nb))
            except Exception:
                # Fallback: write raw JSON
                zf.writestr(filename, json.dumps(nb_dict, indent=2))

        # requirements.txt
        zf.writestr("requirements.txt", "\n".join(sorted(all_requirements)))

        # README.md
        zf.writestr("README.md", _build_readme(paper_title, lab_entries))

    return buf.getvalue()
